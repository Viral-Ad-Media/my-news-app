import { test, expect } from '@playwright/test';
import { readFileSync } from 'node:fs';
const content = readFileSync('tests/fixtures/full-article.txt', 'utf8');

test('editor curates an event and homepage; reader follows, compares, mutes, reports and controls reading', async ({ page }) => {
  test.setTimeout(180000);
  await page.addInitScript(() => localStorage.setItem('news-location', 'ng'));
  const headers = { Origin: 'http://127.0.0.1:3216' };
  async function login(admin = true) {
    await page.goto(admin ? '/admin/login' : '/login');
    await page.getByLabel('Username or email', { exact: true }).fill(admin ? 'admin-e2e' : 'reader-e2e');
    await page.getByLabel('Password', { exact: true }).fill(admin ? 'test-admin-e2e-only' : 'test-reader-e2e-only');
    await page.getByRole('button', { name: 'Sign in', exact: true }).click();
    await expect(page).toHaveURL(admin ? /\/admin$/ : /\/dashboard$/);
  }
  async function create(path: string, data: object) {
    const res = await page.request.post(`/api/admin/${path}`, { headers, data });
    expect(res.status()).toBe(201); return res.json();
  }
  await login();
  const category = await create('categories', { name: 'Editorial Integration', slug: 'editorial-integration' });
  const source = await create('sources', { name: 'Editorial First Publisher', url: 'https://example.org', location: 'ng', enabled: false });
  const secondSource = await create('sources', { name: 'Editorial Second Publisher', url: 'https://example.com', location: 'ng', enabled: false });
  const first = await create('articles', { title: 'Editorial event opening report', description: 'A source report used only in disposable tests.', content, source: source.id, categories: [category.id], location: 'ng', article_url: 'https://example.org/event', why_matters: 'This development affects access to services in the selected country.', context_source_url: 'https://example.org/context', image_credit: 'Test image credit', editorial_type: 'analysis' });
  const second = await create('articles', { title: 'Editorial event follow-up report', description: 'A second attributed report for comparison.', content, source: secondSource.id, categories: [category.id], location: 'ng', article_url: 'https://example.com/event' });
  await page.goto('/admin/editorial');
  await page.getByRole('button', { name: 'Create story', exact: true }).click();
  await page.getByLabel('Title', { exact: true }).fill('Country services developing event');
  await page.getByLabel('What happened — sourced overview').fill('An editor-curated event supported by two linked source reports.');
  await page.getByLabel('What remains uncertain (optional)').fill('The next implementation date has not been confirmed.');
  await page.getByLabel('Search published articles').fill('Editorial event');
  await page.getByRole('checkbox', { name: new RegExp(first.title) }).check();
  await page.getByRole('checkbox', { name: new RegExp(second.title) }).check();
  await page.getByRole('switch', { name: 'Publish event page' }).check();
  await page.getByRole('button', { name: 'Save editorial changes' }).click();
  await expect(page.getByRole('status')).toHaveText('Editorial changes saved.');
  const storyData = await (await page.request.get('/api/admin/editorial/stories')).json();
  const story = storyData.results.find((s: { title: string }) => s.title === 'Country services developing event');
  expect(story.report_ids).toHaveLength(2);
  await page.getByRole('button', { name: 'Timeline updates', exact: true }).click();
  await page.getByRole('button', { name: 'Create record', exact: true }).click();
  await page.getByLabel('Search published articles').fill(second.title);
  await page.getByRole('radio', { name: new RegExp(second.title) }).check();
  await page.getByLabel('Developing story', { exact: true }).selectOption(String(story.id));
  await page.getByLabel('What changed — supported by the selected report').fill('The second publisher reported a new development.');
  await page.getByRole('button', { name: 'Save editorial changes' }).click();
  await expect(page.getByRole('status')).toHaveText('Editorial changes saved.');
  await page.getByRole('button', { name: 'Homepage stories', exact: true }).click();
  await page.getByRole('button', { name: 'Create record', exact: true }).click();
  await page.getByLabel('Search published articles').fill(first.title);
  await page.getByRole('radio', { name: new RegExp(first.title) }).check();
  await page.getByRole('button', { name: 'Save editorial changes' }).click();
  await expect(page.getByRole('status')).toHaveText('Editorial changes saved.');
  await page.getByRole('button', { name: 'Corrections', exact: true }).click();
  await page.getByRole('button', { name: 'Create record', exact: true }).click();
  await page.getByLabel('Search published articles').fill(first.title);
  await page.getByRole('radio', { name: new RegExp(first.title) }).check();
  await page.getByLabel('Public correction / clarification').fill('Clarification: the source refers to a proposal, not a completed change.');
  await page.getByRole('button', { name: 'Save editorial changes' }).click();
  await expect(page.getByRole('status')).toHaveText('Editorial changes saved.');
  for (const width of [390, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: `test-results/editorial-admin-${width}.png`, fullPage: true });
  }
  await page.goto('/admin/coverage');
  await expect(page.getByRole('heading', { name: 'Every edition, accounted for' })).toBeVisible();
  await page.getByLabel('Category', { exact: true }).selectOption(String(category.id));
  await expect(page.getByRole('cell', { name: '2 / 2', exact: true })).toBeVisible();
  await page.request.delete('/api/session', { headers });
  await login(false);
  await page.request.put('/api/reader/reader-choices', { headers, data: { categories: [], sources: [], muted_sources: [], stories: [] } });
  await page.goto('/');
  await expect(page.locator('.lead-story h3')).toHaveText(first.title);
  await page.goto(`/news/${first.id}`);
  await expect(page.getByRole('heading', { name: 'Why this matters' })).toBeVisible();
  await expect(page.getByText('Clarification: the source refers to a proposal, not a completed change.')).toBeVisible();
  await page.getByRole('button', { name: 'Follow this story', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Following story', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.goto(`/stories/${story.id}`);
  await expect(page.getByRole('heading', { name: 'Compare reports', exact: true })).toBeVisible();
  await expect(page.getByRole('heading', { name: first.title })).toBeVisible();
  await expect(page.getByRole('heading', { name: second.title })).toBeVisible();
  await expect(page.getByText('The second publisher reported a new development.')).toBeVisible();
  await page.goto(`/news/${first.id}`);
  await page.getByRole('button', { name: 'Show less: mute publisher' }).click();
  await expect(page.getByRole('button', { name: 'Unmute publisher' })).toBeVisible();
  await page.goto('/feed');
  await expect(page.getByRole('heading', { name: second.title })).toBeVisible();
  await expect(page.getByRole('heading', { name: first.title })).toHaveCount(0);
  await expect(page.getByText('Why this story: You follow this developing story.')).toBeVisible();
  await page.getByText('Reading settings', { exact: true }).click();
  await page.getByLabel('Article text size').selectOption('largest');
  await page.getByRole('checkbox', { name: 'Low-data mode — hide news images' }).check();
  await page.getByRole('checkbox', { name: 'Remember reading history when signed in' }).check();
  await page.goto(`/news/${second.id}`);
  await expect(page.locator('html')).toHaveAttribute('data-reading-size', 'largest');
  await expect(page.locator('.news-photo img')).toHaveCount(0);
  await page.getByText('Report an error', { exact: true }).click();
  await page.getByLabel('What should our editors check?').fill('Please verify the date against the original source report.');
  await page.getByRole('button', { name: 'Send for editorial review' }).click();
  await expect(page.getByRole('status').filter({ hasText: 'editorial review queue' })).toBeVisible();
  for (const width of [390, 768, 1440]) {
    await page.setViewportSize({ width, height: 1000 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: `test-results/editorial-reader-${width}.png`, fullPage: true });
  }
  await page.goto('/history');
  await expect(page.getByRole('heading', { name: second.title })).toBeVisible();
  await page.getByRole('button', { name: 'Clear all countries’ reading history' }).click();
  await expect(page.getByText('No reading history in this edition.')).toBeVisible();
  await page.goto(`/sources/${source.id}`);
  await expect(page.getByText('Unrated — no documented rating has been assigned.')).toBeVisible();
  await page.request.delete('/api/session', { headers });
  await login();
  await page.goto('/admin/editorial');
  await page.getByRole('button', { name: 'Reader reports', exact: true }).click();
  await expect(page.getByRole('cell', { name: 'Please verify the date against the original source report.' })).toBeVisible();
});
