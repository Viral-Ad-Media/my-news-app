import { readFileSync } from 'node:fs';
import { test, expect } from '@playwright/test';
const content = readFileSync('tests/fixtures/full-article.txt', 'utf8');

test('real reader can register, read, follow a category, save and unsave a story without admin access', async ({ page }) => {
  test.setTimeout(90000);
  await page.addInitScript(() => localStorage.setItem('news-location', 'ng'));
  await page.goto('/admin/login');
  await page.getByLabel('Username or email').fill('admin-e2e');
  await page.getByLabel('Password', { exact: true }).fill('test-admin-e2e-only');
  await page.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Dashboard', exact: true })).toBeVisible();
  const headers = { Origin: 'http://127.0.0.1:3216' };
  const categoryResponse = await page.request.post('/api/admin/categories', { headers, data: { name: 'Reader Journey', slug: 'reader-journey', description: '' } });
  expect(categoryResponse.status()).toBe(201);
  const category = await categoryResponse.json();
  const sourceResponse = await page.request.post('/api/admin/sources', { headers, data: { name: 'Reader Journey Publisher', url: 'https://example.org', location: 'ng', enabled: false } });
  expect(sourceResponse.status()).toBe(201);
  const source = await sourceResponse.json();
  const articleResponse = await page.request.post('/api/admin/articles', { headers, data: { title: 'Public reader integration report', description: 'A disposable integration fixture, never published to production.', content, source: source.id, categories: [category.id], location: 'ng', article_url: 'https://example.org/readiness-fixture' } });
  expect(articleResponse.status()).toBe(201);
  const article = await articleResponse.json();
  expect((await page.request.delete('/api/session', { headers })).status()).toBe(200);
  await page.goto('/signup');
  await page.getByLabel('Username', { exact: true }).fill('public-readiness-reader');
  await page.getByLabel('Email address', { exact: true }).fill('readiness-reader@example.test');
  await page.getByLabel('Password', { exact: true }).fill('X8!pQ3#tV7@mL2zR5');
  await page.getByLabel('Confirm password', { exact: true }).fill('X8!pQ3#tV7@mL2zR5');
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await expect(page).toHaveURL(/\/dashboard$/);
  await expect(page.getByRole('heading', { name: 'Welcome back, public-readiness-reader' })).toBeVisible();
  expect((await page.request.get('/api/admin/dashboard')).status()).toBe(403);
  await page.goto(`/categories/${category.id}`);
  await expect(page.getByRole('heading', { name: category.name, level: 1 })).toBeVisible();
  await expect(page.getByRole('heading', { name: article.title })).toBeVisible();
  await page.goto(`/news/${article.id}`);
  await expect(page.getByRole('heading', { name: article.title, level: 1 })).toBeVisible();
  await page.getByRole('button', { name: 'Save', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Unsave', exact: true })).toHaveAttribute('aria-pressed', 'true');
  await page.goto('/news/saved');
  await expect(page.getByRole('heading', { name: article.title })).toBeVisible();
  await page.goto('/topics?manage=1');
  await page.getByRole('checkbox', { name: category.name, exact: true }).check();
  await page.getByRole('button', { name: 'Save Topics', exact: true }).click();
  await expect(page.getByRole('status').filter({ hasText: 'Topics saved.' })).toBeVisible();
  await page.goto('/feed');
  await expect(page.getByRole('heading', { name: article.title })).toBeVisible();
  await page.goto('/live');
  await expect(page.getByRole('heading', { name: article.title })).toBeVisible();
  await page.goto('/news/saved');
  await page.getByRole('button', { name: 'Unsave', exact: true }).click();
  await expect(page.getByRole('heading', { name: article.title })).toHaveCount(0);
  await page.goto('/dashboard');
  await page.getByRole('button', { name: 'Sign Out', exact: true }).click();
  await expect(page).toHaveURL(/\/$/);
  expect((await page.context().cookies()).some(cookie => cookie.name === 'news_access')).toBe(false);
});
