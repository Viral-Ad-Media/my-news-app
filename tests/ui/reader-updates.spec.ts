import { test, expect } from '@playwright/test';
const now = new Date('2026-10-27T12:00:00Z');
const stories = [2, 30, 120, 480, -1].map((age, i) => ({id: 500+i, location:'ng', title:`Timeline ${age} hours`, description:'Browser test story', published_at:new Date(now.getTime()-age*3600000).toISOString(), source:{name:'Test publisher'}, categories:[{id:1,name:'Science'}]}));
test.beforeEach(async ({ page }) => {
 await page.clock.install({time:now});
 await page.addInitScript(() => localStorage.setItem('news-location','ng'));
 await page.route('http://news-api.test/api/**', route => route.fulfill({json:{results:route.request().url().includes('categories') ? [{id:1,name:'Science'},{id:2,name:'Technology'}] : stories,count:5}}));
 await page.route('**/api/session', route => route.fulfill({json:{username:'Test reader'}}));
 await page.route('**/api/reader/saved-status**', route => route.fulfill({json:{saved_ids:[]}}));
 await page.route('**/api/reader/preferences', route => route.fulfill({json:{categories:[1]}}));
});
test('homepage recap and category links lead into the current topic interface', async ({ page }) => {
 await page.goto('/');
 const ai = page.getByRole('region',{name:'Ask Aboki AI'}), recap = page.getByRole('region',{name:'Briefing Recap'});
 await expect(recap).toBeVisible();
 expect((await recap.boundingBox())!.y).toBeGreaterThan((await ai.boundingBox())!.y);
 await page.locator('.explore-categories').getByRole('link',{name:'Science',exact:true}).click();
 await expect(page).toHaveURL(/topics\?category=Science/);
 const selected = page.getByRole('navigation',{name:'News categories'}).getByRole('link',{name:'Science',exact:true});
 await expect(selected).toHaveAttribute('aria-current','page');
 await expect(selected).toHaveCSS('background-color','rgb(217, 71, 24)');
 await page.getByRole('button',{name:'Manage followed categories'}).click();
 await expect(page.getByRole('checkbox',{name:'Science',exact:true})).toBeChecked();
 await page.getByRole('button',{name:'Manage followed categories'}).click();
 await page.getByRole('contentinfo').getByRole('link',{name:'Choose your topics'}).click();
 await expect(page.getByRole('checkbox',{name:'Science',exact:true})).toBeVisible();
 await page.goto('/feed');
 await page.getByRole('main').getByRole('link',{name:'Choose your topics'}).click();
 await expect(page).toHaveURL(/topics\?manage=1/);
 await expect(page.getByRole('heading',{name:'Choose Your Topics'})).toBeVisible();
});
test('timeline windows never display older or future dated stories even from an old API', async ({ page }) => {
 await page.goto('/timelines');
 await page.getByRole('button',{name:'Last 24 Hours',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Timeline 2 hours'})).toBeVisible();
 for (const age of [30,120,480,-1]) await expect(page.getByRole('heading',{name:`Timeline ${age} hours`,exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Past 7 Days',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Timeline 120 hours'})).toBeVisible();
 await expect(page.getByRole('heading',{name:'Timeline 480 hours'})).toHaveCount(0);
 await page.getByRole('button',{name:'Past 30 Days',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Timeline 480 hours'})).toBeVisible();
});
test('Ask Aboki renders news as links and general answers as text, with recoverable failures', async ({ page }) => {
 let kind = 'news';
 await page.route('**/api/reader/ask', route => kind === 'error' ? route.fulfill({status:503,json:{detail:'AI is temporarily unavailable'}}) : route.fulfill({json:kind === 'news' ? {kind:'news',answer:'This text must not be duplicated',sources:[{id:500,title:'Stored reporting link'}]} : {kind:'general',answer:'Photosynthesis uses light energy.',sources:[]}}));
 await page.goto('/'); const ai=page.getByRole('region',{name:'Ask Aboki AI'});
 await ai.getByRole('textbox',{name:'Question'}).fill('Latest reporting');
 await ai.getByRole('button',{name:'Ask',exact:true}).click();
 await expect(ai.getByRole('link',{name:'Stored reporting link'})).toHaveAttribute('href','/news/500');
 await expect(ai.getByText('This text must not be duplicated')).toHaveCount(0);
 kind='general'; await ai.getByRole('textbox',{name:'Question'}).fill('Explain photosynthesis');
 await ai.getByRole('button',{name:'Ask',exact:true}).click();
 await expect(ai.getByRole('status')).toContainText('Photosynthesis uses light energy.');
 await expect(ai.getByRole('link')).toHaveCount(0);
 kind='error'; await ai.getByRole('button',{name:'Ask',exact:true}).click();
 await expect(ai.getByRole('alert')).toContainText('temporarily unavailable');
 await expect(ai.getByRole('button',{name:'Ask',exact:true})).toBeEnabled();
});
